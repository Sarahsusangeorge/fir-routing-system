/**
 * Copies the Tesseract OCR assets out of node_modules and into public/, so
 * the browser loads them from this origin rather than from a CDN.
 *
 * By default tesseract.js fetches its worker, its WebAssembly core and the
 * English language data from jsdelivr and tessdata.projectnaptha.com at the
 * moment a complainant scans a document. That is third-party code executing
 * against a police system, and a third party learning that a scan happened.
 * Both are avoided by serving the files ourselves; src/services/ocr.ts points
 * tesseract.js at the copies this script makes.
 *
 * The copies are build output, not source: they are gitignored and recreated
 * by `npm run dev` and `npm run build`.
 *
 * tesseract.js chooses one core variant at runtime from the browser's SIMD
 * support, so every variant has to be present even though only one is
 * fetched. A deployment that knows its browsers can prune the rest.
 */

import { createRequire } from "node:module";
import { cp, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const out = path.join(root, "public", "tesseract");

function packageDir(name) {
  return path.dirname(require.resolve(`${name}/package.json`));
}

async function main() {
  await rm(out, { recursive: true, force: true });
  await mkdir(path.join(out, "lang"), { recursive: true });

  // 1. The worker script tesseract.js spawns.
  const worker = path.join(packageDir("tesseract.js"), "dist", "worker.min.js");
  await cp(worker, path.join(out, "worker.min.js"));

  // 2. The WebAssembly core, every variant the runtime may select.
  const coreDir = packageDir("tesseract.js-core");
  const cores = (await readdir(coreDir)).filter((f) => f.endsWith(".wasm.js"));
  if (cores.length === 0) {
    throw new Error("No tesseract.js-core .wasm.js files found; is tesseract.js-core installed?");
  }
  await Promise.all(cores.map((f) => cp(path.join(coreDir, f), path.join(out, f))));

  // 3. English language data. tesseract.js appends "<lang>.traineddata.gz".
  const langDir = path.join(packageDir("@tesseract.js-data/eng"), "4.0.0");
  await cp(path.join(langDir, "eng.traineddata.gz"), path.join(out, "lang", "eng.traineddata.gz"));

  await writeFile(
    path.join(out, "README.txt"),
    "Generated by scripts/vendor-ocr.mjs. Do not edit or commit; run `npm run vendor:ocr` to rebuild.\n",
    "utf8"
  );

  console.log(`Vendored OCR assets into public/tesseract (${cores.length} core variants, 1 language).`);
}

main().catch((err) => {
  console.error("Could not vendor the OCR assets:", err.message);
  process.exit(1);
});
