--   1-3   non-cognizable or bailable, under 3 years
--
-- Definitional sections (2, 3, 4, 5, 13, 299, 300, 320, 375, 415) and
-- procedural provisions that appear in the corpus through citation parsing
-- (155, 156, 161, 164, 173, 190, 200, 482) carry low weights: they are cited
-- alongside a substantive offence rather than charged alone, so they must not
-- drive the priority of a complaint.
--
